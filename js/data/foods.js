/**
 * Food catalogue — around 420 everyday foods.
 *
 * Every food stores macros per 100g. Everything the app shows is derived from
 * these numbers × the weight you entered, so changing a quantity anywhere
 * recomputes the whole meal.
 *
 * Conventions:
 *  - Weights are RAW / AS-BOUGHT unless the name says "cooked". Raw is what you
 *    can actually weigh before it goes in the pan.
 *  - `carbs` is available carbohydrate, UK label style. Fibre is separate and is
 *    NOT included in the carb figure.
 *  - Values are typical UK supermarket / composition-table figures, good to
 *    about ±5% — well inside the noise of home cooking.
 *  - Frying adds the oil you used, not magic calories. Add the oil as its own
 *    line and you'll be close.
 */

const G = [{ id: 'g', label: 'g', grams: 1 }];
const ML = [{ id: 'ml', label: 'ml', grams: 1 }];

function food(id, name, group, [cal, protein, carbs, fat, fibre], measures = G, defaultMeasure = null) {
  return {
    id,
    name,
    group,
    per100: { cal, protein, carbs, fat, fibre },
    measures,
    defaultMeasure: defaultMeasure || measures[0].id,
  };
}

/** Unit measures first, grams always available as a fallback. */
function units(...defs) {
  return [...defs.map(([id, label, grams]) => ({ id, label, grams })), ...G];
}
function liquid(...defs) {
  return [...defs.map(([id, label, grams]) => ({ id, label, grams })), ...ML];
}

