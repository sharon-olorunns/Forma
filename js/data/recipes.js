/**
 * The built-in recipe rotation, taken from The Kitchen · Two Meals.
 *
 * Each recipe is a list of quantified ingredients rather than a fixed macro
 * figure, so changing a quantity or swapping an ingredient recomputes the whole
 * thing. `makes` is the number of portions the full ingredient list produces.
 *
 * `guide` holds the figure printed in the original PDF. Forma computes its own
 * totals from the ingredients; where the two differ, the computed number is the
 * one to trust (see README, "About the numbers").
 */

/** Shorthand: item(ingredientId, qty, measureId, note?) */
function it(ing, qty, measure, note) {
  return note ? { ing, qty, measure, note } : { ing, qty, measure };
}

